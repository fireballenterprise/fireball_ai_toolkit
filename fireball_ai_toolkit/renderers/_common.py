"""Shared helpers for the per-tool renderers.

Every renderer writes markdown that starts with :data:`GENERATED_HEADER` and returns the paths it
wrote. :func:`write_doc` handles the header placement (after frontmatter, never before it — a
leading HTML comment would break frontmatter parsing). :func:`clean_dir` removes files a renderer
no longer produces so a dropped canonical slug's stale output disappears on the next render.

Instruction stubs are **pointer stubs**: provider frontmatter + the header + one
:func:`canonical_pointer` line back to ``.fireball_ai_toolkit/`` or ``.<repo>/``. Skills are the
exception: Copilot and Claude run the skill text itself, so ``SKILL.md`` carries the full body
(:func:`skill_body`) plus any bundle resources, with a source-of-truth line at the end.
"""

from __future__ import annotations

import json
import re
import shutil
from collections.abc import Iterable, Mapping
from pathlib import Path

from ..catalog import ContentBundle, Skill

GENERATED_HEADER = (
    "<!-- DO NOT EDIT. Generated by fireball_ai_toolkit — edit the `.fireball_ai_toolkit/` source, not this "
    "file. Run `invoke ai_toolkit.sync`. -->"
)


def canonical_pointer(bundle: ContentBundle, slug: str, kind: str) -> str:
    """The stub body pointing a provider file at its canonical source.

    ``kind`` is ``instructions`` | ``skills``. Resolves to ``.<repo>/`` (the
    bundle's ``local_name``) when the slug came from the consuming repo's overlay, else
    ``.fireball_ai_toolkit/``.
    """
    if bundle.is_local(slug):
        return f"Source of truth: `.{bundle.local_name}/{kind}/{slug}.md`"
    return f"Source of truth: `.fireball_ai_toolkit/{kind}/{slug}.md`"


def skill_body(bundle: ContentBundle, skill: Skill) -> str:
    """The body of a rendered ``SKILL.md``: the full slash-command text from the canonical skill,
    then its trigger phrases and ``instructions`` paths expanded into a "read and follow" block,
    then the source-of-truth line.

    Claude Code and Copilot reject unknown frontmatter keys, so ``hints`` and ``instructions`` are
    materialised into the body rather than carried as keys.
    """
    parts = [skill.body.strip()] if skill.body.strip() else []
    if skill.hints:
        parts.append("**Also use this skill when the user says**\n" + "\n".join(f"- {hint}" for hint in skill.hints))
    if skill.instructions:
        parts.append(
            "When this skill fires, read and follow:\n\n" + "\n".join(f"- `{path}`" for path in skill.instructions)
        )
    parts.append(canonical_pointer(bundle, skill.name, "skills"))
    return "\n\n".join(parts)


def skill_frontmatter(skill: Skill, *, allowed_tools: bool = False) -> dict[str, object]:
    """The ``SKILL.md`` frontmatter shared by Copilot and Claude Code (``name`` == folder name).

    Both invocation keys are always written explicitly (``user-invocable: true``, ``disable-model-invocation: false`` by default).
    """
    fm: dict[str, object] = {
        "name": skill.name,
        "description": skill.description,
        "argument-hint": skill.argument_hint,
    }
    fm["user-invocable"] = "true" if skill.user_invocable else "false"
    fm["disable-model-invocation"] = "false" if skill.ai_invocable else "true"
    if allowed_tools:
        fm["allowed-tools"] = ", ".join(derive_allowed_tools(skill))
    return fm


def render_skill_folders(bundle: ContentBundle, skills_dir: Path, *, allowed_tools: bool = False) -> list[Path]:
    """Write ``<skills_dir>/<name>/SKILL.md`` for every skill, copy a bundle's resource files next
    to it (relative paths kept), and delete anything there that is no longer produced — stale
    skills, and resources that disappeared from a bundle."""
    written: list[Path] = []
    for skill in bundle.skills:
        folder = skills_dir / skill.name
        written.append(
            write_doc(
                folder / "SKILL.md",
                skill_body(bundle, skill),
                frontmatter=skill_frontmatter(skill, allowed_tools=allowed_tools),
            )
        )
        for rel in skill.resources:
            dest = folder / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes((skill.bundle_dir / rel).read_bytes())  # type: ignore[operator]
            written.append(dest)
    clean_tree(skills_dir, written)
    return written


def clean_tree(directory: Path, keep: Iterable[Path]) -> None:
    """Delete every file under ``directory`` not in ``keep``, then prune emptied directories."""
    if not directory.is_dir():
        return
    keep_set = {p.resolve() for p in keep}
    for path in directory.rglob("*"):
        if path.is_file() and path.resolve() not in keep_set:
            path.unlink()
    for path in sorted((d for d in directory.rglob("*") if d.is_dir()), reverse=True):
        if not any(path.iterdir()):
            path.rmdir()
    if not any(directory.iterdir()):
        directory.rmdir()


def remove_generated(directory: Path, *, suffix: str = ".md") -> None:
    """Remove ``*<suffix>`` files in ``directory`` that carry :data:`GENERATED_HEADER` (a previous
    toolkit version's output, e.g. ``.claude/commands/``, ``.github/prompts/``), then the directory
    itself if that left it empty. Hand-written files are never touched."""
    if not directory.is_dir():
        return
    keep = []
    for path in directory.rglob("*"):
        if not path.is_file():
            continue
        if path.name.endswith(suffix) and GENERATED_HEADER in path.read_text(encoding="utf-8", errors="ignore"):
            path.unlink()
        else:
            keep.append(path)
    clean_tree(directory, keep)


_YAML_UNSAFE = re.compile(r"(^[\s>@`|*&!%#\"'\[{-])|(:\s)|(\s#)|(^$)")


def _scalar(value: str) -> str:
    """Render a string as a YAML scalar, double-quoting only when a bare scalar would be unsafe."""
    return json.dumps(value) if _YAML_UNSAFE.search(value) else value


def render_frontmatter(fields: Mapping[str, object]) -> str:
    """A deterministic YAML frontmatter block (no surrounding ``---``). Keys keep insertion order.

    ``str`` values are bare unless unsafe; ``list``/``tuple`` values become block sequences; empty
    values are skipped entirely.
    """
    lines: list[str] = []
    for key, value in fields.items():
        if value in (None, "", (), []):
            continue
        if isinstance(value, (list, tuple)):
            lines.append(f"{key}:")
            lines.extend(f"  - {_scalar(str(item))}" for item in value)
        else:
            lines.append(f"{key}: {_scalar(str(value))}")
    return "\n".join(lines)


def write_doc(path: Path, body: str, *, frontmatter: Mapping[str, object] | None = None) -> Path:
    """Write ``path`` with the generated header, optional frontmatter, and ``body``. Returns ``path``."""
    path.parent.mkdir(parents=True, exist_ok=True)
    parts: list[str] = []
    if frontmatter:
        block = render_frontmatter(frontmatter)
        if block:
            parts.append(f"---\n{block}\n---\n")
    parts.append(GENERATED_HEADER)
    parts.append("")
    parts.append(body.strip() + "\n")
    path.write_text("\n".join(parts), encoding="utf-8")
    return path


def clean_dir(directory: Path, keep: Iterable[Path], *, suffix: str = ".md") -> None:
    """Delete ``*<suffix>`` files under ``directory`` that are not in ``keep``. No-op if absent."""
    if not directory.is_dir():
        return
    keep_set = {p.resolve() for p in keep}
    for path in directory.rglob(f"*{suffix}"):
        if path.resolve() not in keep_set:
            path.unlink()


def clean_subdirs(parent: Path, keep_names: Iterable[str]) -> None:
    """Remove immediate child directories of ``parent`` whose name is not in ``keep_names``."""
    if not parent.is_dir():
        return
    keep = set(keep_names)
    for child in parent.iterdir():
        if child.is_dir() and child.name not in keep:
            shutil.rmtree(child)


_AWS_PREFIX = re.compile(r"^(AWS_PROFILE=\S+) uv run")


def derive_allowed_tools(command: Skill) -> list[str]:
    """The Claude Code ``allowed-tools`` globs for a skill.

    Explicit canonical ``allowed-tools`` frontmatter wins. Otherwise derive from the body's
    ``!`...``` exec lines: ``uv run --no-sync …`` → ``Bash(uv run --no-sync *)``,
    ``AWS_PROFILE=X uv run …`` → that plus the bare ``uv run`` glob, ``./setup.sh`` →
    ``Bash(./setup.sh)``. No exec line → no entry (the skill is prose-only).
    """
    if command.allowed_tools:
        return list(command.allowed_tools)
    tools: list[str] = []
    for line in command.exec_lines:
        if line.startswith("./setup.sh"):
            _add(tools, "Bash(./setup.sh)")
        elif match := _AWS_PREFIX.match(line):
            _add(tools, f"Bash({match.group(1)} uv run --no-sync *)")
            _add(tools, "Bash(uv run --no-sync *)")
        elif line.startswith("uv run"):
            _add(tools, "Bash(uv run --no-sync *)")
    return tools


def _add(items: list[str], value: str) -> None:
    if value not in items:
        items.append(value)
